/** Exercise the forced-password and durable-preference journey against the real backend. */
import { randomBytes } from 'node:crypto';
import { test, expect } from './fixtures';
test.use({ identityOptions: { role: 'Administrator', mustChangePassword: true }, expectedHttpErrors: [401, 403] });
for (const viewport of [{ width: 1280, height: 800 }, { width: 390, height: 844 }]) {
  test(`profile password gate and persistence at ${viewport.width}px`, async ({ page, identity, browserErrors }) => {
    await page.setViewportSize(viewport);
    await page.goto('/profile'); // sole entry; subsequent navigation uses visible links
    await expect(page.getByRole('heading', { name: 'Sign in' })).toBeVisible();
    await page.getByLabel('Email').fill(identity.email);
    await page.getByLabel('Password', { exact: true }).fill(identity.password);
    const login = page.waitForResponse((response) => response.url().endsWith('/api/auth/login'));
    await page.getByRole('button', { name: 'Sign in', exact: true }).click();
    const loggedIn = await login;
    expect(loggedIn.status()).toBe(200);
    const session = await loggedIn.json();
    expect(session.user.id).toBe(identity.id);
    expect(session.user.mustChangePassword).toBe(true);
    await expect(page.getByRole('heading', { name: 'Secure your account' })).toBeVisible();
    await expect(page.getByRole('link', { name: 'My profile' })).toHaveCount(0);
    await page.getByRole('button', { name: 'Change password', exact: true }).click();
    await expect(page.getByText('Confirm your new password', { exact: true })).toBeVisible();
    const replacement = randomBytes(24).toString('base64url');
    await page.getByLabel('Current password', { exact: true }).fill('wrong-credential');
    await page.getByLabel('New password', { exact: true }).fill(replacement);
    await page.getByLabel('Confirm new password', { exact: true }).fill(replacement);
    const denied = page.waitForResponse((response) => response.url().endsWith('/api/auth/change-password'));
    await page.getByRole('button', { name: 'Change password', exact: true }).click();
    const rejected = await denied;
    expect(rejected.status()).toBe(403);
    expect((await rejected.json()).error.code).toBe('FORBIDDEN');
    await expect(page.getByText('Current password is incorrect', { exact: true })).toBeVisible();
    await expect(page.getByRole('heading', { name: 'Secure your account' })).toBeVisible();
    await page.getByLabel('Current password', { exact: true }).fill(identity.password);
    await page.getByLabel('New password', { exact: true }).fill(replacement);
    await page.getByLabel('Confirm new password', { exact: true }).fill(replacement);
    const change = page.waitForResponse((response) => response.url().endsWith('/api/auth/change-password'));
    await page.getByRole('button', { name: 'Change password', exact: true }).click();
    const changed = await change;
    expect(changed.status()).toBe(200);
    const user = await changed.json();
    expect(user.id).toBe(identity.id);
    expect(user.mustChangePassword).toBe(false);
    expect(user.passwordHash).toBeUndefined();
    expect(JSON.stringify(user)).not.toContain(replacement);
    await page.getByRole('link', { name: 'My profile', exact: true }).click();
    await expect(page.getByRole('heading', { name: user.name })).toBeVisible();
    await expect(page.getByText(user.email, { exact: true })).toBeVisible();
    await expect(page.getByText(user.role, { exact: true })).toBeVisible();
    await expect(page.getByText('All portfolios', { exact: true })).toBeVisible();
    await page.getByLabel('Default landing page').selectOption('profile');
    const preference = page.waitForResponse((response) => response.url().endsWith('/api/auth/preferences'));
    await page.getByRole('button', { name: 'Save preference' }).click();
    const saved = await preference;
    expect(saved.status()).toBe(200);
    expect(saved.request().method()).toBe('PUT');
    expect((await saved.json()).defaultLandingPage).toBe('profile');
    await expect(page.getByText('Preference saved', { exact: true })).toBeVisible();
    await page.getByRole('link', { name: 'Session', exact: true }).click();
    await page.getByRole('link', { name: 'My profile', exact: true }).click();
    const restore = page.waitForResponse((response) => response.url().endsWith('/api/auth/me'));
    await page.reload();
    const persisted = await restore;
    expect(persisted.status()).toBe(200);
    expect((await persisted.json()).defaultLandingPage).toBe('profile');
    await expect(page.getByLabel('Default landing page')).toHaveValue('profile');
    await identity.verifyProfile(replacement, 'profile');
    await page.screenshot({ path: test.info().outputPath('profile.png') });
    await page.getByRole('button', { name: 'Sign out' }).click();
    await expect(page.getByRole('heading', { name: 'Sign in' })).toBeVisible();
    await page.getByLabel('Email').fill(identity.email);
    await page.getByLabel('Password', { exact: true }).fill(replacement);
    const relogin = page.waitForResponse((response) => response.url().endsWith('/api/auth/login'));
    await page.getByRole('button', { name: 'Sign in', exact: true }).click();
    const signedIn = await relogin;
    expect(signedIn.status()).toBe(200);
    expect((await signedIn.json()).user.mustChangePassword).toBe(false);
    await expect(page.getByRole('heading', { name: 'My profile' })).toBeVisible();
    expect(browserErrors).toEqual([]);
  });
}
